ENDPOINTS = {"gun_knife": {"gun", "knife"}, "gun": {"gun"}, "all_labels": None}


def target_mask(frame, endpoint):
    wanted = ENDPOINTS[endpoint]
    return frame.truth_set.map(lambda values: bool(values) if wanted is None else bool(values & wanted))


def prepare():
    _, first, pilot, source = load_data()
    first = first.copy()
    first["route"] = np.where(first.open | first.human, "B", np.where(first.machine, "K", "U"))
    second = pilot[pilot.GROUP.eq("NoAI")].copy()
    # A request remains a request even when its source button revealed truth.
    second["refer"] = second.open | second.human
    referral = second.groupby("image").refer.mean()
    first["second_referral"] = first.image.map(referral)
    assert first.second_referral.notna().all()
    groups = sorted(set(second.groupby("image").person.apply(frozenset)), key=lambda s: sorted(s))
    assert len(groups) == 2 and all(len(g) == 10 for g in groups) and not groups[0] & groups[1]
    parameters = []
    for endpoint in ENDPOINTS:
        positive = target_mask(first, endpoint)
        empty = ~first.truth
        p = {"endpoint": endpoint, "positive_n": int(positive.sum()), "empty_n": int(empty.sum())}
        for route in ["B", "K", "U"]:
            p[route + "_positive_n"] = int((positive & first.route.eq(route)).sum())
            p[route + "_empty_n"] = int((empty & first.route.eq(route)).sum())
            p[route + "_positive"] = p[route + "_positive_n"] / p["positive_n"]
            p[route + "_empty"] = p[route + "_empty_n"] / p["empty_n"]
            g = first[positive & first.route.eq(route)]
            p[route + "_reader_detection"] = float(g.second_referral.mean()) if len(g) else 0.
            g = first[empty & first.route.eq(route)]
            p[route + "_reader_empty_referral"] = float(g.second_referral.mean()) if len(g) else 0.
        parameters.append(p)
    profiles = []
    u = first[first.route.eq("U")].copy()
    for number, people in enumerate(itertools.product(*[sorted(g) for g in groups]), 1):
        lookup = second[second.person.isin(people)].set_index("image")
        assert lookup.index.is_unique
        d = u.join(lookup[["refer", "open", "human"]], on="image", rsuffix="_second")
        for endpoint in ENDPOINTS:
            positive = target_mask(d, endpoint)
            profiles.append(dict(profile=number, endpoint=endpoint, pool=len(d),
                target_records=int(positive.sum()), target_referrals=int((positive & d.refer).sum()),
                physical_referrals=int(d.refer.sum()), truth_requests=int(d.open_second.sum()),
                alarms=int(d.human_second.sum()),
                target_truth_requests=int((positive & d.open_second).sum())))
    return first, second, pd.DataFrame(parameters), pd.DataFrame(profiles), source


def cascade(p, q, db, dk, du, su, policy, prevalence=.001):
    sk = 1. if policy == "retain_alarm" else p["K_reader_detection"]
    fk = 1. if policy == "retain_alarm" else p["K_reader_empty_referral"]
    risk = p["B_positive"]*(1-db) + p["K_positive"]*(1-sk*dk) + p["U_positive"]*(1-q*su*du)
    base = prevalence*p["B_positive"] + (1-prevalence)*p["B_empty"]
    gate = prevalence*p["K_positive"]*sk + (1-prevalence)*p["K_empty"]*fk
    u_phys = prevalence*p["U_positive"]*su + (1-prevalence)*p["U_empty"]*p["U_reader_empty_referral"]
    gate_reads = 0. if policy == "retain_alarm" else prevalence*p["K_positive"]+(1-prevalence)*p["K_empty"]
    u_reads = prevalence*p["U_positive"]+(1-prevalence)*p["U_empty"]
    return dict(conditional_final_miss=risk, base_physical_per_scan=base,
        gate_physical_per_scan=gate, U_physical_per_scan_at_full=u_phys,
        physical_per_scan=base+gate+q*u_phys,
        gate_reads_per_scan=gate_reads, U_reads_per_scan_at_full=u_reads,
        reads_per_scan=gate_reads+q*u_reads)


def needed_q(p, target, db, dk, du, su, policy):
    initial = cascade(p, 0., db, dk, du, su, policy)["conditional_final_miss"]
    benefit = p["U_positive"]*su*du
    if initial <= target+1e-12:
        return 0.
    value = (initial-target)/benefit if benefit else math.inf
    return 1. if abs(value-1.) <= 1e-12 else value


def all_success(mean, rho, count):
    if count == 0:
        return 1.
    if mean in [0., 1.]:
        return mean
    if rho == 0.:
        return mean**count
    if rho == 1.:
        return mean
    concentration = 1/rho-1
    return float(np.exp(betaln(mean*concentration+count, (1-mean)*concentration)
                        -betaln(mean*concentration, (1-mean)*concentration)))


def proof_checks():
    rng = np.random.default_rng(202610141)
    paths = 0
    for _ in range(120):
        a, r = rng.dirichlet([1, 1, 1])[:2]
        p = {"B_positive": 1-a-r, "K_positive": a, "U_positive": r,
             "K_reader_detection": rng.random(), "K_reader_empty_referral": .2,
             "B_empty": .1, "K_empty": .2, "U_empty": .7, "U_reader_empty_referral": .3}
        q, db, dk, du, su = rng.random(5)
        for policy in ["retain_alarm", "second_reader_clearance"]:
            sk = 1. if policy == "retain_alarm" else p["K_reader_detection"]
            enumerated = (1-a-r)*(1-db)
            for chosen, detected_read, detected_phys in itertools.product([0, 1], repeat=3):
                w = (q if chosen else 1-q)*(su if detected_read else 1-su)*(du if detected_phys else 1-du)
                enumerated += r*w*(not (chosen and detected_read and detected_phys))
            enumerated += a*(1-sk*dk)
            actual = cascade(p, q, db, dk, du, su, policy)["conditional_final_miss"]
            assert np.isclose(enumerated, actual)
            paths += 1
    selection = 0
    for n in range(1, 8):
        for b in range(n+1):
            for positives in range(min(n, 3)+1):
                # Prefix target events all trigger physical inspection.
                for calls in range(positives, n+1):
                    for limit in [0, calls//2, calls]:
                        outcomes = [all(i in selected for i in range(positives)) and
                                    sum(i < calls for i in selected) <= limit
                                    for selected in itertools.combinations(range(n), b)]
                        formula = 0.
                        if b >= positives:
                            h = hypergeom.pmf(positives, n, positives, b)
                            cdf = (float(limit >= positives) if n == positives else
                                   hypergeom.cdf(limit-positives, n-positives, calls-positives, b-positives))
                            formula = h*cdf
                        assert np.isclose(np.mean(outcomes), formula)
                        selection += 1
    # Three-event capture bounds; intersection min/max verified by joint LP.
    lp_cases = 0
    states = np.array(list(itertools.product([0., 1.], repeat=3)))
    objective = states.prod(axis=1)
    for margins in [[.2, .8, .9], [.95, .95, .95], [1., .99, .99], [.4, .4, .4]]:
        constraints = np.vstack([np.ones(8), states.T])
        for sign, expected in [(1, max(0, sum(margins)-2)), (-1, min(margins))]:
            result = linprog(sign*objective, A_eq=constraints, b_eq=np.r_[1, margins], bounds=(0, None), method="highs")
            assert result.success and np.isclose(sign*result.fun, expected)
            lp_cases += 1
    return dict(passed=True, cascade_enumerations=paths, finite_joint_enumerations=selection,
                three_event_linear_programs=lp_cases)


def bootstrap_primary(first, repetitions):
    rng = np.random.default_rng(202610142)
    people = first[["person", "stratum"]].drop_duplicates().reset_index(drop=True)
    images = first[["image", "truth", "error", "difficulty"]].drop_duplicates().reset_index(drop=True)
    ip = pd.Categorical(first.person, categories=people.person).codes
    ix = pd.Categorical(first.image, categories=images.image).codes
    target = target_mask(first, "gun_knife")
    masks = np.column_stack([target, target & first.route.eq("K"), target & first.route.eq("U")]).astype(float)
    draws = []
    with threadpool_limits(limits=4):
        for start in range(0, repetitions, 128):
            size = min(128, repetitions-start)
            pw = np.ones((size, len(people))); iw = np.ones((size, len(images)))
            for ids in people.groupby("stratum").indices.values():
                pw[:, ids] = rng.multinomial(len(ids), np.repeat(1/len(ids), len(ids)), size=size)
            for ids in images.groupby(["truth", "error", "difficulty"]).indices.values():
                iw[:, ids] = rng.multinomial(len(ids), np.repeat(1/len(ids), len(ids)), size=size)
            counts = (pw[:, ip]*iw[:, ix]) @ masks
            for total, k, u in counts:
                a, r = k/total, u/total
                base = 1-a-r
                risk = base*.0001+a*.01+r*.01
                required = max(0, base*.0001+a*.01+r-.001)/(r*.99) if r else (0. if base*.0001+a*.01 <= .001 else math.inf)
                draws.append(dict(a=a, r=r, full_coverage_final_miss=risk, required_q=required, feasible=required <= 1))
    return pd.DataFrame(draws)


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--smoke", action="store_true")
    args = ap.parse_args(); started = time.time()
    out = BASE / "results" / ("conditional_theory_smoke" if args.smoke else "conditional_theory")
    out.mkdir(parents=True, exist_ok=True)
    if not args.smoke:
        assert json.loads((BASE/"results/conditional_theory_smoke/verification.json").read_text())["passed"]
    checks = proof_checks()
    first, second, parameters, profiles, source = prepare()
    parameters.to_csv(out/"source_route_parameters.csv", index=False)
    profiles.to_csv(out/"source_person_profile_counts.csv", index=False)
    cur = BASE/"data/curated/conditional_theory"; cur.mkdir(parents=True, exist_ok=True)
    if not args.smoke:
        first[["image", "truth", "machine", "human", "open", "route", "second_referral"]].to_csv(cur/"source_first_stage_routes.csv", index=False)
    requirements = []; surfaces = []; constraints = []
    points = 11 if args.smoke else 201
    for p in parameters.to_dict("records"):
        for policy in ["retain_alarm", "second_reader_clearance"]:
            for db, d, su, target in itertools.product([.99, .999, .9999, 1.], [.9, .95, .99, 1.], [.8, .95, 1.], [.0001, .001, .005, .01]):
                q = needed_q(p, target, db, d, d, su, policy)
                value = cascade(p, min(q, 1.), db, d, d, su, policy)
                requirements.append(dict(endpoint=p["endpoint"], policy=policy, base_detection=db,
                    backup_detection=d, U_reader_detection=su, target=target, required_coverage=q,
                    feasible=q <= 1., **value))
                assert (value["conditional_final_miss"] <= target+1e-12) == (q <= 1.+1e-12), (p["endpoint"], policy, db, d, su, target, q, value)
            for prevalence, su, q in itertools.product([.0001, .001, .01], [.8, .95, 1.], np.linspace(0, 1, points)):
                surfaces.append(dict(endpoint=p["endpoint"], policy=policy, prevalence=prevalence,
                    base_detection=.9999, backup_detection=.99, U_reader_detection=su, coverage=q,
                    **cascade(p, q, .9999, .99, .99, su, policy, prevalence)))
            for lambda_scan, readers, inspectors, read_time, inspect_time in itertools.product([500, 1000, 2000], [4, 8, 16], [20, 40, 80], [10, 20], [60, 120, 240]):
                state = cascade(p, 0., .9999, .99, .99, 1., policy)
                mu_read = readers*3600/read_time/lambda_scan
                mu_phys = inspectors*3600/inspect_time/lambda_scan
                q_read = ((mu_read-state["gate_reads_per_scan"])/state["U_reads_per_scan_at_full"]
                          if state["U_reads_per_scan_at_full"] else math.inf)
                phys0 = state["base_physical_per_scan"]+state["gate_physical_per_scan"]
                q_phys = ((mu_phys-phys0)/state["U_physical_per_scan_at_full"]
                          if state["U_physical_per_scan_at_full"] else math.inf)
                qmin = needed_q(p, .001, .9999, .99, .99, 1., policy)
                qmax = min(1., q_read, q_phys)
                constraints.append(dict(endpoint=p["endpoint"], policy=policy, hourly_scans=lambda_scan,
                    readers=readers, inspectors=inspectors, read_seconds=read_time, inspect_seconds=inspect_time,
                    required_coverage=qmin, stable_coverage_upper=qmax,
                    feasible_with_strict_slack=qmin <= 1 and qmin < q_read and qmin < q_phys))
    pd.DataFrame(requirements).to_csv(out/"cascade_target_feasibility.csv", index=False)
    pd.DataFrame(surfaces).to_csv(out/"cascade_risk_workload_surface.csv", index=False)
    pd.DataFrame(constraints).to_csv(out/"conditional_capacity_feasibility.csv", index=False)
    joint_rows = []; dependence = []
    budgets = [0, 122, 238, 244] if args.smoke else np.arange(245)
    limits = [80] if args.smoke else [40, 60, 80, 100, 120, 160]
    for p in parameters.to_dict("records"):
        g = profiles[profiles.endpoint.eq(p["endpoint"])]
        assert g.target_records.eq(g.target_referrals).all()
        n = int(g.pool.iloc[0]); btarget = int(g.target_records.iloc[0]); ktarget = p["K_positive_n"]
        oc = g.physical_referrals.to_numpy(int)
        for budget, limit in itertools.product(budgets, limits):
            h = float(hypergeom.pmf(btarget, n, btarget, budget))
            requests_cdf = (hypergeom.cdf(limit-9-btarget, n-btarget, oc-btarget, budget-btarget)
                            if budget >= btarget else np.zeros(len(g)))
            for d, rho in itertools.product([.95, .99], [0., .1, .5, 1.]):
                moment = all_success(d, rho, ktarget+btarget)
                probability = h*float(np.mean(requests_cdf))*moment
                joint_rows.append(dict(endpoint=p["endpoint"], review_count=budget,
                    physical_request_limit=limit, physical_detection=d, inspection_correlation=rho,
                    expected_missed_targets=ktarget*(1-d)+btarget*(1-budget/n*d),
                    expected_physical_requests=9+budget/n*float(oc.mean()),
                    probability_no_target_miss_and_calls_within_limit=probability,
                    probability_any_target_miss=1-h*moment,
                    baseline_B_conditioned_contained=True))
        for d, rho in itertools.product([.95, .99], [0., .02, .1, .5, 1.]):
            count = ktarget+btarget
            dependence.append(dict(endpoint=p["endpoint"], targets=count, physical_detection=d,
                inspection_correlation=rho, expected_misses=count*(1-d),
                probability_any_miss=1-all_success(d, rho, count),
                probability_every_target_missed=all_success(1-d, rho, count)))
    pd.DataFrame(joint_rows).to_csv(out/"finite_cascade_joint_outcomes.csv", index=False)
    pd.DataFrame(dependence).to_csv(out/"shared_inspection_state.csv", index=False)
    # Aggregate sensitivity is insufficient to identify both reader and physical overlap.
    bounds = []
    for p in parameters.to_dict("records"):
        r = p["U_positive"]
        for sr, sp, q in itertools.product([.9, .95, .99], [.9, .95, .99], [0., .5, 1.]):
            capture_low, capture_high = max(0., r+sr+sp-2), min(r, sr, sp)
            bounds.append(dict(endpoint=p["endpoint"], reader_population_detection=sr,
                physical_population_detection=sp, coverage=q, U_miss_low=r-q*capture_high,
                U_miss_high=r-q*capture_low, U_miss_if_independent=r*(1-q*sr*sp)))
    pd.DataFrame(bounds).to_csv(out/"three_event_population_bounds.csv", index=False)
    reps = 64 if args.smoke else 4000
    bootstrap = bootstrap_primary(first, reps)
    bootstrap.to_csv(out/"crossed_bootstrap_primary.csv", index=False)
    summary = []
    for name in ["a", "r", "full_coverage_final_miss", "required_q"]:
        values = bootstrap[name].replace([np.inf, -np.inf], np.nan).dropna()
        summary.append(dict(metric=name, low=values.quantile(.025), high=values.quantile(.975), valid=len(values), repetitions=reps))
    pd.DataFrame(summary).to_csv(out/"crossed_bootstrap_intervals.csv", index=False)
    holdouts = []
    target = target_mask(first, "gun_knife")
    for group in ["image", "person"]:
        for excluded in first[group].unique():
            d = first[first[group].ne(excluded)]
            positive = target.loc[d.index]
            a = float((positive & d.route.eq("K")).sum()/positive.sum())
            r = float((positive & d.route.eq("U")).sum()/positive.sum())
            b = 1-a-r
            q = max(0, b*.0001+a*.01+r-.001)/(r*.99) if r else (0. if b*.0001+a*.01 <= .001 else math.inf)
            holdouts.append(dict(excluded_unit=group, omitted_index=len(holdouts)+1,
                positive_n=int(positive.sum()), a=a, r=r, required_q=q))
    pd.DataFrame(holdouts).to_csv(out/"leave_cluster_out_sensitivity.csv", index=False)
    nominal = parameters[parameters.endpoint.eq("gun_knife")].iloc[0].to_dict()
    selected = {policy: dict(q=needed_q(nominal, .001, .9999, .99, .99, 1., policy),
        full=cascade(nominal, 1., .9999, .99, .99, 1., policy))
        for policy in ["retain_alarm", "second_reader_clearance"]}
    checks.update(smoke=args.smoke, seconds=time.time()-started,
        scenario_grid_rows=len(requirements), risk_surface_rows=len(surfaces), capacity_rows=len(constraints),
        finite_joint_rows=len(joint_rows), bootstrap_repetitions=reps,
        primary_counts={k:nominal[k] for k in ["positive_n", "empty_n", "B_positive_n", "K_positive_n", "U_positive_n"]},
        nominal=selected, source_doi=source["data_DOI"], source_sha256=source["source_sha256"],
        physical_detection_and_service_are_scenario_inputs=True,
        source_truth_requests_are_not_field_service_times=True,
        endpoint_negative_class="Source images with empty target annotation; other tool-only images excluded from primary scale calibration.",
        theory_scope="Conditional fixed-record transport and specified inspection-state model.")
    (out/"verification.json").write_text(json.dumps(checks, indent=2, allow_nan=False), encoding="utf-8")
    print(json.dumps(checks, indent=2))


if __name__ == "__main__":
    main()
